//! UI-only translations. Paths, persistent identifiers, shell commands and
//! user-entered names must never pass through this catalog.
use std::sync::atomic::{AtomicBool, Ordering};

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Language {
    Chinese,
    English,
}
static CHINESE: AtomicBool = AtomicBool::new(true);
pub fn language() -> Language {
    if CHINESE.load(Ordering::Relaxed) {
        Language::Chinese
    } else {
        Language::English
    }
}
pub fn load_language() {
    let saved = super::config_dir().and_then(|d| std::fs::read_to_string(d.join("language")).ok());
    CHINESE.store(
        saved.as_deref().map(str::trim) != Some("en"),
        Ordering::Relaxed,
    );
}
pub fn set_language(language: Language) {
    CHINESE.store(language == Language::Chinese, Ordering::Relaxed);
    if let Some(dir) = super::config_dir() {
        let _ = std::fs::create_dir_all(&dir);
        let _ = std::fs::write(
            dir.join("language"),
            if language == Language::Chinese {
                "zh-CN"
            } else {
                "en"
            },
        );
    }
}
pub fn tr(text: &str) -> &str {
    if language() == Language::English {
        return text;
    }
    chinese(text)
}
